function initialLocale(): Locale {
  if (typeof window === 'undefined') return 'zh'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  return stored === 'en' || stored === 'zh' ? stored : 'zh'
}

export const locale = ref<Locale>(initialLocale())

watch(
  locale,
  (value) => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = value === 'zh' ? 'zh-CN' : 'en'
    }
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, value)
    }
  },
  { immediate: true },
)

export const localeLabel = computed(() => (locale.value === 'zh' ? '中文' : 'EN'))

export function toggleLocale() {
  locale.value = locale.value === 'zh' ? 'en' : 'zh'
}

export function t(key: keyof typeof messages.zh, values: Record<string, string | number> = {}) {
  const activeMessages: Record<string, string> = messages[locale.value]
  const fallbackMessages: Record<string, string> = messages.zh
  let template = activeMessages[key] ?? fallbackMessages[key] ?? key
  for (const [name, value] of Object.entries(values)) {
    template = template.split(`{${name}}`).join(String(value))
  }
  return template
}

/** Split an i18n string by newlines, for use as template arrays (e.g. LLM prompts). */
export function tLines(key: keyof typeof messages.zh, values: Record<string, string | number> = {}) {
  return t(key, values).split('\n')
}

